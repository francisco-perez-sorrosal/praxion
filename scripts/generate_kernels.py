"""Generate the per-role kernels: the process each spawned agent needs, cut from the rules.

`python3 scripts/generate_kernels.py [--check] [--repo-root DIR]` reads the audience manifest
(`rules/_audience.yaml`), the always-loaded sources it classifies and the authored texts under
`claude/kernels/src/`, and writes under `claude/kernels/`:

- one file per module: `core.md` (the three universal blocks, then the rest of the core) and
  one for each declared module; a module above the 10,000-character cap arrives as
  `<module>-<n>.md` parts cut at paragraph ends, whose concatenation is the module (the first
  part of the core carries the contract, because the blocks come first);
- `core-blocks.md`: the three universal blocks, the part of the core every agent definition
  carries as its fallback;
- `principles.md`: the principles of the template's `## Principles` section, each subsection
  verbatim (the section's own heading and framing sentence are orchestrator-only text, so they
  stay behind), the file the principles pointer names;
- `index.json`: per role the modules in each of its injected strings and the strings
  themselves, packed into the fewest strings under the cap with modules in order and none
  split (the first string opens with the core, blocks included); `slots` is the most strings
  any role has plus a reserve for the working project's own `CLAUDE.md`. The index holds no
  adoption status: the hook reads the plugin's own ledger.

Two more artifacts derive from the same blocks, so nothing written by hand can drift from them:

- every agent definition carries the three universal blocks as generated output (the fallback
  that stays when no hook delivers a kernel): a regeneration rewrites the block paragraphs and
  nothing else, appends a block a definition lacks, and keeps the one per-agent sentence that
  may follow the contract;
- `hooks/_kernel_preamble.py`, the short preamble put ahead of host-native spawns, with its
  contract wording taken from the contract block and its length bounded as it is today.

Text rendered is classified `core` or `role`; `orchestrator-only` and `no-actor` text never is.
Verbatim sections are the source bytes; a condensed entry is its authored text. Every run over
the same sources writes the same bytes. `--check` assembles in memory, writes nothing and exits
1 when anything on disk differs. Exit 0 written or fresh, 1 stale under `--check`, 2 input error.

Every role's strings carry the shared wording verbatim, the partial-output form's `Stopped at`
included; a definition that words its own stop line differently is aligned to it, so a kernel
never carries a label its definition does not.

Stdlib plus PyYAML (read once, in `kernel_model`).
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from collections.abc import Iterator, Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path

import check_agent_shared_blocks as sb
import kernel_model as km
import kernel_sources as ks
from _markdown_tables import code_mask
from _repo_root import is_plugin_cache_path, resolve_repo_root

SCRIPT_DIR = Path(__file__).resolve().parent

KERNELS_DIR = "claude/kernels"
BLOCKS_FILE = "core-blocks.md"
PRINCIPLES_FILE = "principles.md"
PRINCIPLES_HEADING = "Principles"
PRINCIPLES_LEVEL = 2
INDEX_SCHEMA = 1
PROJECT_FILE_RESERVE = 6  # slots kept for the working project's CLAUDE.md, ~10,000 characters each
PARAGRAPH_GAP = "\n\n"
MODULE_JOIN = "+"  # joins the module labels packed into one string

CONTRACT_SOURCE = "rules/swe/agent-behavioral-contract.md"
CONTRACT_HEADING = "Agent Behavioral Contract"
LINKS_TEXT = "praxion-links"
RETURN_TEXT = "return-contract"
BLOCK_TEXTS = frozenset({LINKS_TEXT, RETURN_TEXT})
SELF_TEST_LABEL = "Self-test:"  # opens the contract's last line, in the rule and in the block
BEHAVIOUR_BULLET = "- **"
# The block's first line: it cites the rule, a semantic part of the block that the behaviours
# and the self-test do not carry (the contract check reads the citation in every definition).
CONTRACT_LEAD_IN = f"**Apply the behavioral contract** (`{CONTRACT_SOURCE}`):"

# The slugs of the shared-block checker's universal blocks, which locate them in a definition.
CONTRACT_SLUG = "behavioral-contract"
LINKS_SLUG = "praxion-links"
RETURN_SLUG = "return-contract"

PREAMBLE_PATH = "hooks/_kernel_preamble.py"
PREAMBLE_BOUND = 296  # characters as emitted: the preamble plus the gap before the prompt
PREAMBLE_GAP = "\n\n"
PREAMBLE_TEMPLATE = (
    "[Praxion process active] Apply the behavioral contract: {names}. "
    "Use the tier selector; carry this contract into every delegation. "
    "Return a pointer, not a payload: a summary plus your .ai-work/ "
    "artifact path, not the full report."
)
PREAMBLE_MODULE = '''"""The host-native preamble, generated by scripts/generate_kernels.py from the contract.

Edit the behavioral contract rule and regenerate: the commit gate refuses a stale copy.
"""

_PREAMBLE = {literal}
'''
_BEHAVIOUR_NAME = re.compile(rf"^{re.escape(BEHAVIOUR_BULLET)}(.+?)\*\*", re.MULTILINE)
_PARAGRAPH_BREAK = re.compile(r"(\n\s*\n)")  # capturing, so a split rejoins to the same text


class KernelPlanError(km.KernelModelError):
    """The sources cannot be assembled into kernels."""


@dataclass(frozen=True)
class UniversalBlocks:
    """The three blocks every agent definition carries, each without a trailing newline."""

    contract: str  # lead-in, the rule's behaviours, then its self-test line: consecutive lines
    links: str
    returns: str

    @property
    def text(self) -> str:
        return PARAGRAPH_GAP.join((self.contract, self.links, self.returns))


@dataclass(frozen=True)
class Kernel:
    """The sources as text: the universal blocks and every module, before any splitting."""

    blocks: UniversalBlocks
    modules: Mapping[str, str]  # "core" (blocks first), then each declared module; newline-ended
    principles: str  # the template's Principles section, verbatim


@dataclass(frozen=True)
class RoleAssembly:
    role: str
    modules: tuple[str, ...]  # the modules the role holds, core first
    strings: tuple[km.KernelString, ...]  # as injected, in order


@dataclass(frozen=True)
class KernelPlan:
    files: Mapping[str, bytes]  # repository-relative path -> bytes, everything generated
    roles: Mapping[str, RoleAssembly]

    def assembled_kernel(self, role: str) -> RoleAssembly:
        if role not in self.roles:
            raise KernelPlanError(f"no such role: {role!r}")
        return self.roles[role]


# -- Pure: assembling the text -------------------------------------------------------


def assemble(
    manifest: km.Manifest, sections: Mapping[str, Sequence[ks.Section]], authored: Mapping[str, str]
) -> Kernel:
    texts = km.entry_texts(manifest, sections)
    contract = _contract_entry(manifest)
    placed: dict[str, list[str]] = {name: [] for name in ("core", *manifest.modules)}
    for text in manifest.authored:
        if text.condenses is None and text.id not in BLOCK_TEXTS:
            _place(placed, text.module, authored[text.id], text.id)
    for entry in manifest.entries:
        module = _module_of(entry)
        if module is None or entry is contract or _block_text(entry):
            continue
        body = (
            authored[entry.form.text_ref] if isinstance(entry.form, km.Condensed) else texts[entry]
        )
        _place(placed, module, body, entry.target.heading)
    bare = next((name for name, pieces in placed.items() if name != "core" and not pieces), None)
    if bare:
        raise KernelPlanError(f"module {bare!r} has no text: no entry or authored text places any")
    blocks = UniversalBlocks(
        f"{CONTRACT_LEAD_IN}\n{_contiguous(texts[contract])}",
        authored_block(authored, LINKS_TEXT),
        authored_block(authored, RETURN_TEXT),
    )
    modules = {
        name: PARAGRAPH_GAP.join(t.rstrip("\n") for t in pieces) for name, pieces in placed.items()
    }
    modules["core"] = blocks.text + PARAGRAPH_GAP + modules["core"]
    return Kernel(
        blocks,
        {name: text + "\n" for name, text in modules.items()},
        principles_section(sections),
    )


def principles_section(sections: Mapping[str, Sequence[ks.Section]]) -> str:
    """The subsections of the user template's `## Principles` section, byte for byte.

    The section's own heading and framing sentence are classified orchestrator-only, so the
    file opens at the first principle.
    """
    template = sections.get(ks.USER_TEMPLATE, ())
    start = next(
        (
            i
            for i, section in enumerate(template)
            if (section.level, section.heading) == (PRINCIPLES_LEVEL, PRINCIPLES_HEADING)
        ),
        None,
    )
    if start is None:
        raise KernelPlanError(f"{ks.USER_TEMPLATE} has no '{PRINCIPLES_HEADING}' section")
    end = next(
        (i for i in range(start + 1, len(template)) if template[i].level <= PRINCIPLES_LEVEL),
        len(template),
    )
    return ks.pin_extent("".join(section.text for section in template[start + 1 : end]))


def _contract_entry(manifest: km.Manifest) -> km.AudienceEntry:
    for entry in manifest.entries:
        target = entry.target
        if isinstance(entry.scope, km.Core) and (target.source, target.heading) == (
            CONTRACT_SOURCE,
            CONTRACT_HEADING,
        ):
            return entry
    raise KernelPlanError(f"the core carries no behavioral contract: {CONTRACT_SOURCE} gives none")


def _contiguous(text: str) -> str:
    """The contract's lines as the rule words them, minus the blank line before the self-test."""
    return "\n".join(line.rstrip() for line in text.splitlines() if line.strip())


def authored_block(authored: Mapping[str, str], text_id: str) -> str:
    if text_id not in authored:
        raise KernelPlanError(f"universal block {text_id!r} is not an authored text")
    return authored[text_id].rstrip()


def _module_of(entry: km.AudienceEntry) -> str | None:
    match entry.scope:
        case km.Core():
            return "core"
        case km.Role(module=module):
            return module
        case _:
            return None


def _block_text(entry: km.AudienceEntry) -> bool:
    return isinstance(entry.form, km.Condensed) and entry.form.text_ref in BLOCK_TEXTS


def _place(placed: dict[str, list[str]], module: str, text: str, where: str) -> None:
    if module not in placed:
        raise KernelPlanError(f"{where}: module {module!r} is not declared")
    placed[module].append(text)


def paragraph_atoms(text: str) -> list[str]:
    """`text` cut where a blank-line run (outside code) ends a paragraph; atoms concatenate to it.

    Each cut falls right after the paragraph's own newline, so the blank line that separates
    two paragraphs opens the next atom: a part never ends in a blank line (the end-of-file
    fixer would eat it) and joined parts keep their separators.
    """
    lines = text.splitlines(keepends=True)
    in_code = code_mask([line.rstrip("\r\n") for line in lines])
    line_offsets = [0]
    for line in lines:
        line_offsets.append(line_offsets[-1] + len(line))
    cuts = [
        text.index("\n", len(text[: line_offsets[i]].rstrip())) + 1
        for i in range(1, len(lines))
        if lines[i].strip() and not lines[i - 1].strip() and not in_code[i - 1]
    ]
    return [text[a:b] for a, b in zip([0, *cuts], [*cuts, len(text)], strict=True)]


def split_parts(text: str, cap: int = km.MAX_STRING_CHARS) -> tuple[str, ...]:
    """`text` as the fewest parts of at most `cap` characters, cut at paragraph ends."""
    if len(text) <= cap:
        return (text,)
    parts: list[str] = []
    current = ""
    for atom in paragraph_atoms(text):
        if len(atom) > cap:
            raise KernelPlanError(f"a paragraph of {len(atom)} characters exceeds the {cap} cap")
        if current and len(current) + len(atom) > cap:
            parts.append(current)
            current = ""
        current += atom
    return (*parts, current)


# -- Pure: files, role strings, index --------------------------------------------------


def plan_files(kernel: Kernel) -> tuple[dict[str, str], dict[str, tuple[str, ...]]]:
    """The kernel files by name, and each module's parts."""
    files = {BLOCKS_FILE: kernel.blocks.text + "\n", PRINCIPLES_FILE: kernel.principles}
    parts = {name: split_parts(text) for name, text in kernel.modules.items()}
    for name, pieces in parts.items():
        numbered = len(pieces) > 1
        for number, piece in enumerate(pieces, start=1):
            files[f"{name}-{number}.md" if numbered else f"{name}.md"] = piece
    return files, parts


def compose(
    kernel: Kernel,
    manifest: km.Manifest,
    definitions: Mapping[str, str],
) -> KernelPlan:
    files, parts = plan_files(kernel)
    roles = {role: _assemble_role(role, manifest, parts) for role in sorted(definitions)}
    slots = max(len(r.strings) for r in roles.values()) + PROJECT_FILE_RESERVE if roles else 0
    index = _render_index(files, roles, slots)
    encoded = {f"{KERNELS_DIR}/{name}": text.encode("utf-8") for name, text in files.items()}
    encoded[km.INDEX_PATH] = index.encode("utf-8")
    return KernelPlan(encoded, roles)


def _assemble_role(
    role: str, manifest: km.Manifest, parts: Mapping[str, tuple[str, ...]]
) -> RoleAssembly:
    names = ("core", *(m for m in manifest.modules if role in _members(manifest, m)))
    units = [(label, text.strip()) for label, text in _units(names, parts)]
    return RoleAssembly(role, names, _pack(role, units))


def _members(manifest: km.Manifest, module: str) -> frozenset[str]:
    return frozenset(
        agent for name in manifest.modules[module] for agent in manifest.groups.get(name, (name,))
    )


def _units(names: Sequence[str], parts: Mapping[str, tuple[str, ...]]) -> Iterator[tuple[str, str]]:
    """(label, text) per module part a role holds, the core's first part (blocks first) first."""
    for name in names:
        for number, part in enumerate(parts[name], start=1):
            yield (name if len(parts[name]) == 1 else f"{name}-{number}"), part


def _pack(role: str, units: Sequence[tuple[str, str]]) -> tuple[km.KernelString, ...]:
    """Units in order into the fewest strings under the cap; a unit is never split."""
    groups: list[tuple[list[str], str]] = []
    for label, text in units:
        if groups and len(groups[-1][1]) + len(PARAGRAPH_GAP) + len(text) <= km.MAX_STRING_CHARS:
            labels, held = groups[-1]
            groups[-1] = ([*labels, label], held + PARAGRAPH_GAP + text)
        else:
            groups.append(([label], text))
    return tuple(
        km.KernelString(role, ordinal, MODULE_JOIN.join(labels), None, text)
        for ordinal, (labels, text) in enumerate(groups, start=1)
    )


def _render_index(files: Mapping[str, str], roles: Mapping[str, RoleAssembly], slots: int) -> str:
    body = {
        "schema": INDEX_SCHEMA,
        "kernel_version": _kernel_version(files, roles),
        "slots": slots,
        "roles": {
            name: {
                "modules": [s.module for s in role.strings],
                "strings": [s.text for s in role.strings],
            }
            for name, role in roles.items()
        },
    }
    return json.dumps(body, indent=2, ensure_ascii=False) + "\n"


def _kernel_version(files: Mapping[str, str], roles: Mapping[str, RoleAssembly]) -> str:
    """sha1 over every generated kernel byte: the files and each role's strings, in name order."""
    digest = hashlib.sha1(usedforsecurity=False)
    for name in sorted(files):
        digest.update(f"{name}\0{files[name]}\0".encode())
    for name in sorted(roles):
        for string in roles[name].strings:
            digest.update(f"{name}\0{string.module}\0{string.text}\0".encode())
    return digest.hexdigest()


# -- Pure: the definitions and the preamble, derived from the blocks ----------------------


def derived_files(kernel: Kernel, definitions: Mapping[str, str]) -> dict[str, bytes]:
    """The definitions with their universal blocks regenerated, and the preamble module."""
    texts = {
        definition_path(name): render_definition(text, kernel.blocks)
        for name, text in definitions.items()
    }
    texts[PREAMBLE_PATH] = render_preamble(kernel.blocks.contract)
    return {path: text.encode("utf-8") for path, text in texts.items()}


def definition_path(name: str) -> str:
    return f"agents/{name}.md"


def render_definition(text: str, blocks: UniversalBlocks) -> str:
    """`text` with each universal block regenerated where it stands; only block lines change.

    A paragraph is a block's when it opens with the block's anchor or carries one of its tells
    (the shared-block checker's own notion of a carrier). A block a definition lacks is appended
    at its end, in the order contract, links, return contract: moving it is the author's choice
    and later runs keep it where it stands.
    """
    pieces = _PARAGRAPH_BREAK.split(text)  # paragraphs at even positions, the breaks between
    wanted = [
        (_shared_block(CONTRACT_SLUG), blocks.contract),
        (_shared_block(LINKS_SLUG), blocks.links),
        (_shared_block(RETURN_SLUG), blocks.returns),
    ]
    placed: set[str] = set()
    for index in range(0, len(pieces), 2):
        paragraph = pieces[index].rstrip("\n")  # the file's last paragraph keeps its final newline
        for shared, block in wanted:
            rewritten = _rewrite_paragraph(paragraph, shared, block)
            if rewritten is not None:
                pieces[index] = rewritten + pieces[index][len(paragraph) :]
                placed.add(shared.slug)
                break
    missing = [block for shared, block in wanted if shared.slug not in placed]
    if not missing:
        return "".join(pieces)
    return PARAGRAPH_GAP.join(["".join(pieces).rstrip("\n"), *missing]) + "\n"


def _shared_block(slug: str) -> sb.SharedBlock:
    for block in sb.SHARED_BLOCKS:
        if block.slug == slug:
            return block
    raise KernelPlanError(f"the shared-block checker has no block {slug!r}")


def _rewrite_paragraph(paragraph: str, shared: sb.SharedBlock, block: str) -> str | None:
    """`block` in place of the block `paragraph` holds; None when it holds none."""
    if shared.slug != CONTRACT_SLUG:
        return block if _carries(paragraph, shared) else None
    tail = _contract_tail(paragraph, shared)
    if tail is None:
        return None
    return f"{block} {tail}" if tail else block


def _carries(paragraph: str, shared: sb.SharedBlock) -> bool:
    return paragraph.startswith(shared.anchor) or any(tell in paragraph for tell in shared.tells)


def _contract_tail(paragraph: str, shared: sb.SharedBlock) -> str | None:
    """The per-agent sentence after the contract in `paragraph`, '' for none; None for no contract.

    The contract stands as one line (the wording a definition carries today, which may run on
    into that sentence) or as the generated lines: the lead-in, behaviours and the self-test,
    which is a question, so what follows its question mark (on that line, or on lines of their
    own) is the sentence.
    """
    if paragraph.startswith(shared.canonical):
        return paragraph[len(shared.canonical) :].strip()
    lines = paragraph.splitlines()
    self_tests = [i for i, line in enumerate(lines) if line.startswith(SELF_TEST_LABEL)]
    opens_generated = bool(lines) and (
        lines[0] == CONTRACT_LEAD_IN or lines[0].startswith(BEHAVIOUR_BULLET)
    )
    if opens_generated and self_tests:
        _, _, after_question = lines[self_tests[-1]].partition("?")
        trailing = [after_question, *lines[self_tests[-1] + 1 :]]
        return " ".join(part.strip() for part in trailing if part.strip())
    return "" if _carries(paragraph, shared) else None


def render_preamble(contract: str) -> str:
    """The preamble module, its contract wording the behaviours the contract block names."""
    names = _BEHAVIOUR_NAME.findall(contract)
    if not names:
        raise KernelPlanError(
            "the contract names no behaviour (a bold bullet): no preamble wording"
        )
    text = PREAMBLE_TEMPLATE.format(names=", ".join(names))
    emitted = len(text) + len(PREAMBLE_GAP)
    if emitted > PREAMBLE_BOUND:
        raise KernelPlanError(f"the preamble is {emitted} characters, over its {PREAMBLE_BOUND}")
    return PREAMBLE_MODULE.format(literal=json.dumps(text, ensure_ascii=False))


# -- Edge: reading the repository, writing the kernels -----------------------------------


def plan_kernels(root: Path) -> KernelPlan:
    """Everything the generator would write for `root`; refuses sources it cannot trust."""
    definitions = km.agent_definitions(root)
    _refuse_misnamed(root, definitions)
    manifest = km.load_manifest(root, definitions)
    sections = _load_sections(root, manifest)
    _refuse(km.check_totality(manifest, sections, ks.always_loaded_sources(root)))
    kernel = assemble(manifest, sections, _read_authored(root, manifest))
    plan = compose(kernel, manifest, definitions)
    return KernelPlan({**plan.files, **derived_files(kernel, definitions)}, plan.roles)


def _refuse_misnamed(root: Path, definitions: Mapping[str, str]) -> None:
    """A definition is written back to the file its `name:` says it is."""
    for name in definitions:
        if not (root / definition_path(name)).is_file():
            raise KernelPlanError(f"agent {name!r} is not defined in {definition_path(name)}")


def _load_sections(root: Path, manifest: km.Manifest) -> dict[str, tuple[ks.Section, ...]]:
    sources = {*ks.always_loaded_sources(root), *(e.target.source for e in manifest.entries)}
    return {s: ks.load_sections(root, s) for s in sorted(sources) if (root / s).is_file()}


def _refuse(findings: Sequence[km.Finding]) -> None:
    if findings:
        shown = "; ".join(f"{f.kind}: {f.subject} {f.detail}".strip() for f in findings[:5])
        raise KernelPlanError(f"{len(findings)} problem(s) in the sources: {shown}")


def _read_authored(root: Path, manifest: km.Manifest) -> dict[str, str]:
    """Each authored text without its one closing newline."""
    texts = {}
    for text in manifest.authored:
        path = root / text.path
        if not path.is_file():
            raise KernelPlanError(f"authored text {text.id!r}: {text.path} does not exist")
        texts[text.id] = path.read_bytes().decode("utf-8").removesuffix("\n")
    return texts


def stale_files(root: Path, files: Mapping[str, bytes]) -> list[str]:
    """Generated paths whose bytes differ on disk, are missing, or are kernel files nobody makes."""
    stale = [rel for rel, data in files.items() if _on_disk(root / rel) != data]
    return sorted({*stale, *_leftovers(root, files)})


def _on_disk(path: Path) -> bytes | None:
    return path.read_bytes() if path.is_file() else None


def _leftovers(root: Path, files: Mapping[str, bytes]) -> list[str]:
    directory = root / KERNELS_DIR
    found = (
        [p.relative_to(root).as_posix() for p in directory.glob("*.md")]
        if directory.is_dir()
        else []
    )
    return [rel for rel in found if rel not in files]


def write_files(root: Path, files: Mapping[str, bytes]) -> list[str]:
    """Write what differs and delete leftover kernel files; the paths touched."""
    touched = stale_files(root, files)
    for rel in touched:
        path = root / rel
        if rel in files:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(files[rel])
        else:
            path.unlink()
    return touched


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate the per-role kernels.")
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 when stale")
    parser.add_argument("--repo-root", help="repository root (defaults to git discovery)")
    args = parser.parse_args(argv)
    try:
        root = resolve_repo_root(args.repo_root, script_dir=SCRIPT_DIR)
        if is_plugin_cache_path(root):
            raise KernelPlanError(f"{root} is an installed-plugin cache: edit the source checkout")
        plan = plan_kernels(root)
        stale = stale_files(root, plan.files) if args.check else write_files(root, plan.files)
    except (
        ValueError,
        km.MissingParserError,
        OSError,
    ) as exc:  # the model's errors are ValueErrors
        print(f"error: {exc}", file=sys.stderr)
        return 2
    for rel in stale:
        print(f"{'stale' if args.check else 'wrote'}: {rel}")
    return 1 if args.check and stale else 0


if __name__ == "__main__":
    sys.exit(main())
