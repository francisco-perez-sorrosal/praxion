from __future__ import annotations

import importlib.util
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[1]
EXPORTER_PATH = REPO_ROOT / "codex" / "config" / "export-codex-agents.py"


def load_exporter():
    spec = importlib.util.spec_from_file_location("export_codex_agents", EXPORTER_PATH)
    assert spec is not None
    assert spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_export_agents_writes_required_codex_fields(tmp_path: Path):
    exporter = load_exporter()
    out_dir = tmp_path / "agents"

    written = exporter.export_agents(REPO_ROOT, out_dir)

    assert written
    researcher = out_dir / "researcher.toml"
    assert researcher in written
    text = researcher.read_text(encoding="utf-8")
    assert text.startswith("# Generated by Praxion Codex exporter.\n")
    assert 'name = "researcher"' in text
    assert "description =" in text
    assert "developer_instructions =" in text
    assert str((REPO_ROOT / "agents" / "researcher.md").resolve()).replace("\\", "/") in text
    assert "source file remains authoritative" in text
    assert "Surface Assumptions" in text  # the core contract, carried by the wrapper
    assert "Partial output." in text  # the role kernel, embedded from the index
    developer_instructions = text.split("developer_instructions =", maxsplit=1)[1]
    assert "You do not implement." not in developer_instructions


def test_export_agents_translates_routing_and_keeps_contract_capsule(tmp_path: Path):
    exporter = load_exporter()
    out_dir = tmp_path / "agents"

    exporter.export_agents(REPO_ROOT, out_dir)

    researcher = (out_dir / "researcher.toml").read_text(encoding="utf-8")
    promethean = (out_dir / "promethean.toml").read_text(encoding="utf-8")

    assert 'model = "gpt-5.4"' in researcher
    assert 'model_reasoning_effort = "medium"' in researcher
    assert "Praxion agent contract:" in researcher

    assert 'model = "gpt-5.5"' in promethean
    assert 'model_reasoning_effort = "high"' in promethean
    assert "tools: Read, Glob, Grep, Bash, Write, Edit, AskUserQuestion, WebFetch" in promethean
    assert "permissionMode:" not in promethean
    assert "hooks:" not in promethean
    assert "Do not duplicate the canonical agent body here." in promethean
    assert str((REPO_ROOT / "agents" / "promethean.md").resolve()).replace("\\", "/") in promethean


def test_parse_rejects_missing_frontmatter(tmp_path: Path):
    exporter = load_exporter()
    path = tmp_path / "bad.md"
    path.write_text("No frontmatter\n", encoding="utf-8")

    with pytest.raises(exporter.AgentParseError, match="missing YAML frontmatter"):
        exporter.parse_frontmatter_agent(path)


WRAPPER_BEGIN = "<!-- codex-wrapper:begin -->"
WRAPPER_END = "<!-- codex-wrapper:end -->"
UNMARKED_ENDING = "Do not duplicate the canonical agent body here. Read it from the source file"


def render_instructions(exporter, passages: list[str]) -> str:
    return exporter.render_developer_instructions(
        "scribe", Path("/x/scribe.md"), ["name: scribe"], ["KERNEL"], passages
    )


def test_a_marked_passage_is_embedded_once_outside_the_capsule():
    exporter = load_exporter()
    body = f"Intro.\n{WRAPPER_BEGIN}\n- run the check\n{WRAPPER_END}\nOutro.\n"

    passages = exporter.extract_wrapper_passages(body, Path("agents/scribe.md"))
    text = render_instructions(exporter, passages)

    assert text.count("- run the check") == 1
    assert text.index("KERNEL") < text.index("- run the check") < text.index("```yaml")
    assert WRAPPER_BEGIN not in text
    assert "Intro." not in text
    assert "beyond the marked passages" in text


def test_two_marked_passages_keep_their_order():
    exporter = load_exporter()
    body = f"{WRAPPER_BEGIN}\nfirst\n{WRAPPER_END}\n{WRAPPER_BEGIN}\nsecond\n{WRAPPER_END}\n"

    passages = exporter.extract_wrapper_passages(body, Path("agents/scribe.md"))

    assert passages == ["first", "second"]


def test_an_unmarked_definition_exports_the_unchanged_wrapper():
    exporter = load_exporter()

    passages = exporter.extract_wrapper_passages("Just a body.\n", Path("agents/scribe.md"))
    text = render_instructions(exporter, passages)

    assert passages == []
    assert text.endswith(f"{UNMARKED_ENDING} when you need the full workflow narrative.")
    assert "marked passages" not in text
    assert text == exporter.render_developer_instructions(
        "scribe", Path("/x/scribe.md"), ["name: scribe"], ["KERNEL"]
    )


@pytest.mark.parametrize(
    ("body", "complaint"),
    [
        (f"{WRAPPER_BEGIN}\nnever closed\n", "unclosed"),
        (f"{WRAPPER_BEGIN}\n{WRAPPER_BEGIN}\n{WRAPPER_END}\n{WRAPPER_END}\n", "nested"),
        (f"text\n{WRAPPER_END}\n", "stray"),
    ],
)
def test_a_malformed_marker_raises_naming_the_file(body: str, complaint: str):
    exporter = load_exporter()

    with pytest.raises(exporter.AgentParseError, match=rf"agents/scribe\.md.*{complaint}"):
        exporter.extract_wrapper_passages(body, Path("agents/scribe.md"))
